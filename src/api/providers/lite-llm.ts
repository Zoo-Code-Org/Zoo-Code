/**
 * LiteLLM provider handler
 *
 * This handler uses the LiteLLM API to proxy requests to various LLM providers.
 * It follows the OpenAI API format for compatibility.
 */
export class LiteLLMHandler extends RouterProvider implements SingleCompletionHandler {
	constructor(options: ApiHandlerOptions) {
		super({
			options,
			name: providerIdentifiers.litellm,
			baseURL: `${options.litellmBaseUrl || "http://localhost:4000"}`,
			apiKey: options.litellmApiKey || "dummy-key",
			modelId: options.litellmModelId,
			defaultModelId: litellmDefaultModelId,
			defaultModelInfo: litellmDefaultModelInfo,
		})
	}

	override getModelCacheScope(): ModelCacheScope {
		return { urlScoped: true, keyScoped: true, authScoped: false }
	}

	async fetchModels(options: GetModelsOptions, signal?: AbortSignal): Promise<ModelRecord> {
		const fetchOpts: [] | [{ signal: AbortSignal }] = signal ? [{ signal }] : []
		return getLiteLLMModels(options.apiKey ?? "", options.baseUrl ?? "", ...fetchOpts)
	}

	private isGpt5(modelId: string): boolean {
		// Match gpt-5, gpt5, and variants like gpt-5o, gpt-5-turbo, gpt5-preview, gpt-5.1
		// Avoid matching gpt-50, gpt-500, etc.
		return /\bgpt-?5(?!\d)/i.test(modelId)
	}

	private getReasoningEffort(info: ModelInfo): ReasoningEffortExtended | undefined {
		const supported = info.supportsReasoningEffort
		if (!Array.isArray(supported)) return undefined

		const configured = this.options.reasoningEffort
		if (configured && configured !== "disable" && supported.includes(configured)) return configured

		const fallback = info.reasoningEffort
		return fallback && supported.includes(fallback) ? fallback : undefined
	}

	/**
	 * Detect if the model is a Gemini model that requires thought signature handling.
	 * Gemini 3 models validate thought signatures for tool/function calling steps.
	 */
	private isGeminiModel(modelId: string): boolean {
		// Match various Gemini model patterns:
		// - gemini-3-pro, gemini-3-flash, gemini-3-*
		// - gemini 3 pro, Gemini 3 Pro (space-separated, case-insensitive)
		// - gemini/gemini-3-*, google/gemini-3-*
		// - vertex_ai/gemini-3-*, vertex/gemini-3-*
		// Also match Gemini 2.5+ models which use similar validation
		const lowerModelId = modelId.toLowerCase()
		return (
			// Match hyphenated versions: gemini-3, gemini-2.5
			lowerModelId.includes("gemini-3") ||
			lowerModelId.includes("gemini-2.5") ||
			// Match space-separated versions: "gemini 3", "gemini 2.5"
			// This handles model names like "Gemini 3 Pro" from LiteLLM model groups
			lowerModelId.includes("gemini 3") ||
			lowerModelId.includes("gemini 2.5") ||
			// Also match provider-prefixed versions
			/\b(gemini|google|vertex_ai|vertex)\/gemini[-\s](3|2\.5)/i.test(modelId)
		)
	}

	/**
	 * Inject thought signatures for Gemini models via provider_specific_fields.
	 * This is required when switching from other models to Gemini to satisfy API validation
	 * for function calls that weren't generated by Gemini (and thus lack thought signatures).
	 *
	 * Per LiteLLM documentation:
	 * - Thought signatures are stored in provider_specific_fields.thought_signature of tool calls
	 * - The bypass token (GEMINI_THOUGHT_SIGNATURE_BYPASS) skips signature validation
	 *
	 * We inject the dummy signature on EVERY tool call unconditionally to ensure Gemini
	 * doesn't complain about missing/corrupted signatures when conversation history
	 * contains tool calls from other models (like Claude).
	 */
	private injectThoughtSignatureForGemini(
		openAiMessages: OpenAI.Chat.ChatCompletionMessageParam[],
	): OpenAI.Chat.ChatCompletionMessageParam[] {
		const dummySignature = GEMINI_THOUGHT_SIGNATURE_BYPASS

		return openAiMessages.map((msg) => {
			if (msg.role === "assistant") {
				const toolCalls = (msg as any).tool_calls as any[] | undefined

				// Only process if there are tool calls
				if (toolCalls && toolCalls.length > 0) {
					// Inject dummy signature into ALL tool calls' provider_specific_fields
					// This ensures Gemini doesn't reject tool calls from other models
					const updatedToolCalls = toolCalls.map((tc) => ({
						...tc,
						provider_specific_fields: {
							...(tc.provider_specific_fields || {}),
							thought_signature: dummySignature,
						},
					}))

					return {
						...msg,
						tool_calls: updatedToolCalls,
					}
				}
			}
			return msg
		})
	}

	override async *createMessage(
		systemPrompt: string,
		messages: Anthropic.Messages.MessageParam[],
		metadata?: ApiHandlerCreateMessageMetadata,
	): ApiStream {
		// Fast-fail if the request was already aborted before building, so an
		// already-aborted request fails with AbortError before provider model
		// discovery (getModels/refreshModels) begins.
		throwIfAborted(metadata?.abortSignal)

		// Model discovery is shared single-flight (RouterProvider.fetchModel):
		// concurrent callers join one in-flight fetch, so the fetch itself
		// carries no request signal — one caller's abort would reject other
		// requests' shared discovery. Cancellation during discovery is a
		// rejectOnAbort race: this request settles promptly with AbortError
		// while the shared fetch keeps running.
		let model: Awaited<ReturnType<LiteLLMHandler["fetchModel"]>>
		try {
			if (metadata?.abortSignal) {
				model = await rejectOnAbort(this.fetchModel(), metadata.abortSignal, "LiteLLM")
			} else {
				model = await this.fetchModel()
			}
		} catch (error) {
			// An abort landing while discovery fails must still surface as the
			// standard AbortError, not the fetcher's generic model-fetch error.
			if (isRequestAborted(error, metadata?.abortSignal)) {
				throw createAbortError("LiteLLM")
			}
			throw error
		}
		const { id: modelId, info } = model

		// Models that require reasoning_content to be echoed back during tool-call
		// continuations (see LITELLM_PRESERVE_REASONING_MODEL_IDS) need convertToR1Format:
		// it merges consecutive same-role messages and, via mergeToolResultText, folds
		// text following tool_results into the last tool message so a user message
		// never gets inserted mid-turn and causes the model to drop prior reasoning_content.
		const openAiMessages = info.preserveReasoning
			? convertToR1Format(messages, {
					normalizeToolCallId: sanitizeOpenAiCallId,
					mergeToolResultText: true,
				})
			: convertToOpenAiMessages(messages, {
					normalizeToolCallId: sanitizeOpenAiCallId,
				})

		// Prepare messages with cache control if enabled and supported
		let systemMessage: OpenAI.Chat.ChatCompletionMessageParam
		let enhancedMessages: OpenAI.Chat.ChatCompletionMessageParam[]

		if (this.options.litellmUsePromptCache && info.supportsPromptCache && !info.requiresResponsesApi) {
			// Create system message with cache control in the proper format
			systemMessage = {
				role: "system",
				content: [
					{
						type: "text",
						text: systemPrompt,
						cache_control: { type: "ephemeral" },
					} as any,
				],
			}

			// Find the last two user messages to apply caching
			const userMsgIndices = openAiMessages.reduce(
				(acc, msg, index) => (msg.role === "user" ? [...acc, index] : acc),
				[] as number[],
			)
			const lastUserMsgIndex = userMsgIndices[userMsgIndices.length - 1] ?? -1
			const secondLastUserMsgIndex = userMsgIndices[userMsgIndices.length - 2] ?? -1

			// Apply cache_control to the last two user messages
			enhancedMessages = openAiMessages.map((message, index) => {
				if ((index === lastUserMsgIndex || index === secondLastUserMsgIndex) && message.role === "user") {
					// Handle both string and array content types
					if (typeof message.content === "string") {
						return {
							...message,
							content: [
								{
									type: "text",
									text: message.content,
									cache_control: { type: "ephemeral" },
								} as any,
							],
						}
					} else if (Array.isArray(message.content)) {
						// Apply cache control to the last content item in the array
						return {
							...message,
							content: message.content.map((content, contentIndex) =>
								contentIndex === message.content.length - 1
									? ({
											...content,
											cache_control: { type: "ephemeral" },
										} as any)
									: content,
							),
						}
					}
				}
				return message
			})
		} else {
			// No cache control - use simple format
			systemMessage = { role: "system", content: systemPrompt }
			enhancedMessages = openAiMessages
		}

		// Required by some providers; others default to max tokens allowed
		const maxTokens: number | undefined = info.maxTokens ?? undefined

		// Check if this is a GPT-5 model that requires max_completion_tokens instead of max_tokens
		const usesMaxCompletionTokens = this.isGpt5(modelId) || info.requiresResponsesApi
		const reasoningEffort = this.getReasoningEffort(info)

		// For Gemini models with native protocol: inject fake reasoning.encrypted block for tool calls
		// This is required when switching from other models to Gemini to satisfy API validation.
		// Gemini 3 models validate thought signatures for function calls, and when conversation
		// history contains tool calls from other models (like Claude), they lack the required
		// signatures. The "skip_thought_signature_validator" value bypasses this validation.
		const isGemini = this.isGeminiModel(modelId)
		let processedMessages = enhancedMessages
		if (isGemini) {
			processedMessages = this.injectThoughtSignatureForGemini(enhancedMessages)
		}

		const requestOptions: OpenAI.Chat.Completions.ChatCompletionCreateParamsStreaming = {
			model: modelId,
			messages: [systemMessage, ...processedMessages],
			stream: true,
			stream_options: {
				include_usage: true,
			},
			tools: this.convertToolsForOpenAI(metadata?.tools),
			tool_choice: metadata?.tool_choice,
		}
		if (reasoningEffort) {
			;(requestOptions as { reasoning_effort?: ReasoningEffortExtended }).reasoning_effort = reasoningEffort
		}

		// Newer OpenAI models require max_completion_tokens instead of the deprecated max_tokens parameter.
		if (usesMaxCompletionTokens && maxTokens) {
			requestOptions.max_completion_tokens = maxTokens
		} else if (maxTokens) {
			requestOptions.max_tokens = maxTokens
		}

		if (info.supportsTemperature !== false && this.supportsTemperature(modelId)) {
			requestOptions.temperature = this.options.modelTemperature ?? 0
		}

		// LiteLLM recognizes X-<vendor>-Session-ID for per-conversation request correlation.
		// This header enables LiteLLM to group related API calls by task for logging and tracing.
		// Unlike Zoo gateways (which use X-Zoo-Task-ID to correlate requests across multiple
		// models within a single conversation), this header is specific to the LiteLLM provider
		// and facilitates provider-level logging and debugging on LiteLLM's admin panel.
		// Matches the convention used by Claude Code (x-claude-code-session-id) and
		// GitHub Copilot (x-copilot-session-id).
		const requestHeaders: Record<string, string> = {}
		if (metadata?.taskId) {
			requestHeaders["X-Zoo-Session-ID"] = metadata.taskId
		}

		// The request-local controller is the provider-owned abort handle; the
		// request signal merges it with the external Task signal (AbortSignal.any
		// inside RequestConfigBuilder), so external aborts cancel the in-flight
		// request without manual listener management.
		const requestBuilder = new RequestConfigBuilder<{ signal?: AbortSignal }>()
		requestBuilder.addMergedSignal(new AbortController(), metadata)
		const requestSignal = requestBuilder.getOption("signal")

		try {
			const { data: completion } = await this.client.chat.completions
				.create(requestOptions, { headers: requestHeaders, signal: requestSignal })
				.withResponse()

			let lastUsage

			for await (const chunk of completion) {
				// Stop consuming buffered chunks once the request is aborted (the
				// OpenAI SDK iterator may keep delivering buffered content after
				// abort, and swallows the mid-stream AbortError).
				if (requestSignal?.aborted) {
					break
				}

				const delta = chunk.choices[0]?.delta
				const usage = chunk.usage as LiteLLMUsage

				const reasoningText = extractReasoningFromDelta(delta)
				if (reasoningText) {
					// No pre-yield guard: this is the first yield of the iteration —
					// the top-of-loop check runs without a suspension point before it.
					yield { type: "reasoning", text: reasoningText }
				}

				if (delta?.content) {
					throwIfAborted(requestSignal)
					yield { type: "text", text: delta.content }
				}

				// Handle tool calls in stream - emit partial chunks for NativeToolCallParser
				if (delta?.tool_calls) {
					for (const toolCall of delta.tool_calls) {
						throwIfAborted(requestSignal)
						yield {
							type: "tool_call_partial",
							index: toolCall.index,
							id: toolCall.id,
							name: toolCall.function?.name,
							arguments: toolCall.function?.arguments,
						}
					}
				}

				if (usage) {
					lastUsage = usage
				}
			}

			// An aborted request must surface as an AbortError, not as a normal
			// stream completion: the top-of-loop break (or a swallowed mid-stream
			// abort) ends the loop without throwing otherwise.
			throwIfAborted(requestSignal)

			if (lastUsage) {
				// Extract cache-related information if available
				// LiteLLM may use different field names for cache tokens
				const cacheWriteTokens =
					lastUsage.cache_creation_input_tokens ||
					lastUsage.prompt_tokens_details?.cache_write_tokens ||
					(lastUsage as any).prompt_cache_miss_tokens ||
					0
				const cacheReadTokens =
					lastUsage.prompt_tokens_details?.cached_tokens ||
					(lastUsage as any).cache_read_input_tokens ||
					(lastUsage as any).prompt_cache_hit_tokens ||
					0

				const { totalCost } = calculateApiCostOpenAI(
					info,
					lastUsage.prompt_tokens || 0,
					lastUsage.completion_tokens || 0,
					cacheWriteTokens,
					cacheReadTokens,
				)

				const usageData: ApiStreamUsageChunk = {
					type: "usage",
					inputTokens: lastUsage.prompt_tokens || 0,
					outputTokens: lastUsage.completion_tokens || 0,
					cacheWriteTokens: cacheWriteTokens > 0 ? cacheWriteTokens : undefined,
					cacheReadTokens: cacheReadTokens > 0 ? cacheReadTokens : undefined,
					totalCost,
				}

				yield usageData
			}
		} catch (error) {
			// Aborted request: covers both the external signal and SDK-native
			// abort errors that may surface before the signal flag propagates.
			if (isRequestAborted(error, metadata?.abortSignal)) {
				throw createAbortError("LiteLLM")
			}
			if (error instanceof Error) {
				throw new Error(`LiteLLM streaming error: ${error.message}`)
			}
			throw error
		}
	}

	async completePrompt(prompt: string, options?: CompletePromptOptions): Promise<string> {
		// Fast-fail if the request was already aborted before building, so an
		// already-aborted request fails with AbortError before provider model
		// discovery (getModels/refreshModels) begins.
		const callerAbortSignal = options?.abortSignal
		throwIfAborted(callerAbortSignal)

		// A single deadline spans model discovery and the completion request:
		// discovery consumes part of the configured timeout, so the SDK call
		// must receive only the remaining budget, not the full timeoutMs.
		// timeoutMs <= 0 means no per-request timeout and no deadline.
		const timeoutMs = getRequestTimeoutMs(options?.timeoutMs)
		const deadline = timeoutMs !== undefined ? Date.now() + timeoutMs : undefined

		// Per the abort-signal series contract, the merged signal (external
		// abort + per-request timeout, timeoutMs <= 0 disabling the timeout)
		// also bounds model discovery: a stalled cold-cache fetch must settle
		// promptly when the caller cancels or the timeout elapses.
		const discoverySignal = mergeAbortSignalAndTimeout(options?.abortSignal, timeoutMs)

		// Model discovery is shared single-flight (RouterProvider.fetchModel):
		// concurrent callers join one in-flight fetch, so the fetch itself
		// carries no request signal — one caller's abort would reject other
		// requests' shared discovery. Cancellation during discovery is a
		// rejectOnAbort race: this request settles promptly while the shared
		// fetch keeps running.
		let model: Awaited<ReturnType<LiteLLMHandler["fetchModel"]>>
		try {
			if (discoverySignal) {
				model = await rejectOnAbort(this.fetchModel(), discoverySignal, "LiteLLM")
			} else {
				model = await this.fetchModel()
			}
		} catch (error) {
			// An abort landing while discovery fails must still surface as the
			// standard AbortError, not the fetcher's generic model-fetch error.
			if (isRequestAborted(error, discoverySignal)) {
				if (discoverySignal?.aborted) {
					// Our merged signal fired: a caller stop surfaces as the
					// standard AbortError, while the per-request timeout
					// elapsing during discovery is a timeout — it must not be
					// misreported as a user cancellation.
					throw callerAbortSignal?.aborted
						? createAbortError("LiteLLM")
						: createTimeoutError("LiteLLM", "model discovery")
				}
				// The signal never aborted: the fetcher itself failed with an
				// AbortError-shaped error; normalize to the standard AbortError.
				throw createAbortError("LiteLLM")
			}
			throw error
		}
		const { id: modelId, info } = model

		// Check if this is a GPT-5 model that requires max_completion_tokens instead of max_tokens
		const usesMaxCompletionTokens = this.isGpt5(modelId) || info.requiresResponsesApi
		const reasoningEffort = this.getReasoningEffort(info)

		// The absolute deadline is enforced THROUGH the SDK call, not just as a
		// per-attempt timeout: the SDK's `timeout` option bounds one attempt,
		// and its default two retries each add a backoff sleep that is not
		// signal-aware (a 30ms budget otherwise elapsed ~1.5s across three
		// attempts). The deadline signal merged with the caller's signal aborts
		// in-flight attempts and makes the SDK's next attempt short-circuit at
		// its pre-flight `signal.aborted` check, and the rejectOnAbort race
		// below settles the caller at the deadline even while the SDK is
		// mid-retry-sleep. Retries stay enabled within the remaining budget.
		const remainingMs =
			deadline !== undefined && Number.isFinite(deadline) ? toSdkTimeoutMs(deadline - Date.now()) : undefined
		// The shared helper applies the series' timeout semantics (cap at 2^31-1 ms,
		// finite positive only) instead of handing a raw delay to AbortSignal.timeout.
		const deadlineSignal = mergeAbortSignalAndTimeout(undefined, remainingMs)

		try {
			const requestOptions: OpenAI.Chat.Completions.ChatCompletionCreateParamsNonStreaming = {
				model: modelId,
				messages: [{ role: "user", content: prompt }],
			}
			if (reasoningEffort) {
				;(requestOptions as { reasoning_effort?: ReasoningEffortExtended }).reasoning_effort = reasoningEffort
			}

			if (info.supportsTemperature !== false && this.supportsTemperature(modelId)) {
				requestOptions.temperature = this.options.modelTemperature ?? 0
			}

			// Newer OpenAI models require max_completion_tokens instead of the deprecated max_tokens parameter.
			if (usesMaxCompletionTokens && info.maxTokens) {
				requestOptions.max_completion_tokens = info.maxTokens
			} else if (info.maxTokens) {
				requestOptions.max_tokens = info.maxTokens
			}

			// Build request options with abortSignal and/or timeout. Per the
			// abort-signal series contract, timeoutMs <= 0 means 'no per-request
			// timeout': the option is omitted entirely, because the OpenAI SDK treats
			// a timeout of 0 as an immediate timeout.
			const createOptions: OpenAI.RequestOptions = {}
			// mergeAbortSignals returns the caller's signal directly when no deadline
			// exists, so one expression covers all four caller/deadline combinations.
			const requestSignal = callerAbortSignal
				? mergeAbortSignals(callerAbortSignal, deadlineSignal)
				: deadlineSignal
			if (requestSignal) {
				createOptions.signal = requestSignal
			}
			if (remainingMs !== undefined) {
				// Only the remaining budget reaches the SDK: model discovery has
				// already consumed part of the configured timeout.
				createOptions.timeout = remainingMs
			}

			const request = this.client.chat.completions.create(
				requestOptions,
				Object.keys(createOptions).length > 0 ? createOptions : undefined,
			)
			// Race the merged signal, not just the deadline: the SDK's retry backoff
			// sleep is not signal-aware, so a caller cancellation during a retry
			// wait must settle immediately instead of waiting the sleep out. The
			// catch above keeps deadline expiry classified as a timeout first.
			const response = requestSignal ? await rejectOnAbort(request, requestSignal, "LiteLLM") : await request
			return response.choices[0]?.message.content || ""
		} catch (error) {
			// Deadline expiry is distinct from caller cancellation: the SDK reports
			// the deadline as an abort-shaped error (APIUserAbortError), so check
			// the deadline first — with the caller still running it must surface as
			// a timeout, never masquerade as the cancellation AbortError.
			if (deadlineSignal?.aborted && !callerAbortSignal?.aborted) {
				throw createTimeoutError("LiteLLM", "completion request")
			}
			// Aborted request: covers both the external signal and SDK-native
			// abort errors that may surface before the signal flag propagates.
			if (isRequestAborted(error, callerAbortSignal)) {
				throw createAbortError("LiteLLM")
			}
			if (error instanceof Error) {
				throw new Error(`LiteLLM completion error: ${error.message}`)
			}
			throw error
		}
	}
}

// LiteLLM usage may include an extra field for Anthropic use cases.
interface LiteLLMUsage extends OpenAI.CompletionUsage {
	cache_creation_input_tokens?: number
	prompt_tokens_details?: OpenAI.CompletionUsage["prompt_tokens_details"] & {
		cache_write_tokens?: number
	}
}
